"""
Generates the phase-2 load scripts from the NFR capacity table (thesis phase 2, 2026-10-22):
  baseline.js            the measured normal load (38 min): 1 -> 2 -> 3 -> 2 -> 1 pods needed
  demo.js                the same shape cut to 22 min, for hand demos (not comparable with measured runs)
  stuck.js, cpuhog.js    a steady load in the 1-pod band for 16 min (the harness injects the fault at 4 min)
  detector_validation.js the phases of detector_validation.sh (replicas set by hand, no agent)
All of them send the request mix of lib/mix.js at an arrival rate (open model). The rates are fractions of the
measured safe rates S1, S2, S3 (5-ml-training/capacity_table.json), chosen so that each phase needs a known pod
count and the scale-down steps sit below the band of the larger count (the 70% anti-flapping deadband):
  L0  = 0.45 S1                         1 pod (also below 0.7 S1: 2 pods there are waste)
  L1  = 1.3 S1                          2 pods (above what 1 pod serves safely, well inside 2 pods' band)
  L2  = (S2 + S3) / 2                   3 pods
  L32 = (S1 + 0.7 S2) / 2               2 pods, and below the 3-pod band (0.7 S2): 3 pods there are waste
  FAULT = 0.6 S1                        1 pod, mid-band
Run once after a new capacity table, then the scripts are FROZEN (committed) for every measured run:
  .venv/bin/python3 4-load-testing/k6/make_profiles.py
"""
import json
import os
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
CAPACITY = os.environ.get("CAPACITY_TABLE", os.path.join(HERE, "..", "..", "5-ml-training", "capacity_table.json"))
OUT_DIR = os.environ.get("OUT_DIR", HERE)   # for a dry run elsewhere

table = {int(k): v for k, v in json.load(open(CAPACITY)).items()}
S1, S2, S3 = (float(table[n]["max_safe_rps"]) for n in (1, 2, 3))
L0, L1, L2 = 0.45 * S1, 1.3 * S1, (S2 + S3) / 2
L32 = (S1 + 0.7 * S2) / 2
FAULT = 0.6 * S1
assert S1 < L1 <= S2 < L2 <= S3, (S1, S2, S3, L1, L2)
if not S1 < L32 < 0.7 * S2:
    print(f"WARNING: no 3->2 step outside the deadband (S1 {S1}, 0.7 S2 {0.7 * S2}); L32 = {L32:.1f}")

HEADER = f"""// GENERATED by make_profiles.py on {date.today()} from 5-ml-training/capacity_table.json
// (safe rps: 1 pod {S1:g}, 2 pods {S2:g}, 3 pods {S3:g}). FROZEN for the measured runs: regenerate only with a new
// capacity table, and say so in the results' notes. The request mix: lib/mix.js; open model (arrival rate).
"""
COMMON = """import {{ loginPool, mixedRequest }} from './lib/mix.js';

export const options = {{
    scenarios: {{
        load: {{ {executor}, timeUnit: '10s', preAllocatedVUs: 200, maxVUs: 3000 }},
    }},
    summaryTrendStats: ['avg', 'p(50)', 'p(95)', 'p(99)', 'max'],
}};

export function setup() {{ return loginPool(); }}
export default function (pool) {{ mixedRequest(pool); }}
"""


def per10(rps):
    return round(rps * 10)


def ramping(stages):
    body = "\n".join(f"                {{ duration: '{d}', target: {per10(r)} }},  // {r:.1f} rps{'  ' + c if c else ''}"
                      for d, r, c in stages)
    return f"executor: 'ramping-arrival-rate', startRate: 0, stages: [\n{body}\n            ]"


def write(name, comment, executor):
    with open(os.path.join(OUT_DIR, name), "w") as f:
        f.write(HEADER + comment + COMMON.format(executor=executor))
    print("wrote", name)


BASELINE = [("2m", L0, "warm-up                      -> 1 pod"), ("3m", L0, "steady"),
            ("4m", L1, "more than 1 pod serves      -> scale UP to 2"), ("4m", L1, ""),
            ("4m", L2, "more than 2 pods serve      -> scale UP to 3"), ("4m", L2, ""),
            ("4m", L32, "3 pods over-provisioned     -> scale DOWN to 2"), ("4m", L32, ""),
            ("4m", L0, "2 pods over-provisioned     -> scale DOWN to 1"), ("5m", L0, "")]
write("baseline.js", f"""// SCENARIO baseline (the measured normal load, 38 min): nothing breaks; the load needs 1 -> 2 -> 3 -> 2 -> 1 pods.
//   L0 {L0:.1f} rps (0.45 S1, 1 pod) -> L1 {L1:.1f} (1.3 S1, 2 pods) -> L2 {L2:.1f} ((S2+S3)/2, 3 pods)
//   -> L32 {L32:.1f} ((S1+0.7 S2)/2, 2 pods; below the 3-pod band) -> L0 (1 pod; below 0.7 S1, the 2-pod band).
//   4-min ramps and holds: long enough for detection, the agent run, its verification and the 90 s settle.
//   Scored by NFR violation, errors, replica-minutes and % of time correctly provisioned (results_nfr.csv).
""", ramping(BASELINE))

DEMO = [("1m", L0, ""), ("2m", L0, ""), ("2m", L1, "-> 2 pods"), ("3m", L1, ""), ("2m", L2, "-> 3 pods"),
        ("3m", L2, ""), ("2m", L32, "-> 2 pods"), ("3m", L32, ""), ("2m", L0, "-> 1 pod"), ("2m", L0, "")]
write("demo.js", "// SCENARIO demo (22 min): the shape of baseline.js cut short for hand demos. Not comparable with measured runs.\n",
      ramping(DEMO))

for fault, what in [("stuck", "POST /chaos/stuck (a leaked DB connection pool: every request waits 3 s, then 503;\n"
                              "//   /ready fails, so the readiness probe takes the pod out of service). New pods are healthy."),
                    ("cpuhog", "POST /chaos/cpuhog (a never-ending job blocks the event loop 600 ms at a time).\n"
                               "//   Looks like CPU overload at a fraction of the capacity.")]:
    write(f"{fault}.js", f"""// SCENARIO {fault}: a steady load in the 1-pod band ({FAULT:.1f} rps = 0.6 S1) for 16 min, so before the fault the right
// number of pods is 1 and no strategy should act. At t = 4 min run_experiment.sh (SCENARIO={fault}) sends
// {what}
// Right fix: a restart. Scored by recovery_s in results_nfr_{fault}.csv. The same load as the other fault script.
""", f"executor: 'constant-arrival-rate', rate: {per10(FAULT)}, duration: '16m'")

B, D = 1.1 * S1, 1.1 * S2
PHASES = [("A", 1, L0, 300, "normal"), ("B", 1, B, 120, "ANOMALY overload"), ("C", 2, B, 300, "normal"),
          ("D", 2, D, 120, "ANOMALY overload"), ("E", 3, D, 300, "normal"), ("F", 3, L32, 180, "ANOMALY waste"),
          ("G", 2, L32, 300, "normal"), ("H", 2, L0, 180, "ANOMALY waste"), ("I", 1, L0, 240, "normal")]
stages, previous = [], 0.0
for phase, reps, rate, seconds, expected in PHASES:
    if rate != previous:
        stages.append((f"10s", rate, f"{phase}: {reps} pod(s), {expected}"))
        seconds -= 10
    stages.append((f"{seconds}s", rate, "" if rate != previous else f"{phase}: {reps} pod(s), {expected}"))
    previous = rate
table_lines = "\n".join(f"//  {p}      {r}        {rate:6.1f}  {s // 60}:{s % 60:02d}   {e}" for p, r, rate, s, e in PHASES)
write("detector_validation.js", f"""// SCENARIO detector validation (no agent, 34 min): every state of baseline.js held long enough to evaluate, with
// the replica count set by hand (detector_validation.sh) and anomaly_detector.py --dry-run logging every reading.
// Overload phases at 1.1 x the safe rate (open model: far beyond it the queue grows without bound).
//  phase  pods  rps     min    expected
{table_lines}
""", ramping(stages))
print(f"S1 {S1} S2 {S2} S3 {S3} | L0 {L0:.1f} L1 {L1:.1f} L2 {L2:.1f} L32 {L32:.1f} FAULT {FAULT:.1f} B {B:.1f} D {D:.1f}")
