def table(df, columns):
    labels = [l for l in ORDER if l in set(df["label"])] + sorted(set(df["label"]) - set(ORDER))
    lines = ["| Metric | " + " | ".join(f"{l} (n={int((df['label'] == l).sum())})" for l in labels) + " |",
             "|---|" + "---|" * len(labels)]
    for col, name in columns:
        cells = []
        for l in labels:
            raw = df.loc[df["label"] == l, col] if col in df else pd.Series(dtype=object)
            never = int((raw.astype(str) == "never").sum())
            v = pd.to_numeric(raw, errors="coerce").dropna()
            if never:
                cells.append(f"never ({never}/{len(raw)})" + (f", else {v.mean():.3g}" if len(v) else ""))
            elif v.empty:
                cells.append("–")
            elif len(v) == 1:
                cells.append(f"{v.iloc[0]:g}")
            else:
                cells.append(f"{v.mean():.3g} ± {v.std():.2g}")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def run_series(r):
    path = os.path.join(ROOT, str(r.get("run_dir") or ""), "series.json")
    if not r.get("run_dir") or not os.path.exists(path):
        return {}
    with open(path) as f:
        return {k: {int(t): v for t, v in s.items()} for k, s in json.load(f).items()}


def timelines(df, out_name, fault=False):
    drawn = [(r, run_series(r)) for _, r in df.reset_index(drop=True).iterrows()]
    drawn = [(r, s) for r, s in drawn if s.get("replicas")]
    if not drawn:
        return f"{out_name}: no run with data, figure not rewritten"
    top_rps = max(max(s["throughput"].values() or [1]) for _, s in drawn) * 1.1
    fig, axes = plt.subplots(len(drawn), 1, figsize=(11, 2.3 * len(drawn)), sharex=True, squeeze=False)
    for i, (r, s) in enumerate(drawn):
        start = datetime.strptime(r["start"], "%Y-%m-%d %H:%M:%S").timestamp()
        ax = axes[i][0]
        t = sorted(s["replicas"])
        ax.step([(x - start) / 60 for x in t], [s["replicas"][x] for x in t], where="post", color="#1f4e79", lw=2)
        tr = sorted(s.get("ready_replicas", {}))
        ax.step([(x - start) / 60 for x in tr], [s["ready_replicas"][x] for x in tr], where="post", color="#1f4e79",
                lw=1, ls=":")
        ax.set_ylim(0, 3.6)
        ax.set_yticks([1, 2, 3])
        ax.set_ylabel("pods")
        ax2 = ax.twinx()
        tt = sorted(s["throughput"])
        ax2.plot([(x - start) / 60 for x in tt], [s["throughput"][x] for x in tt], color="#8a8a8a", lw=1)
        ax2.set_ylim(0, top_rps)
        ax2.set_ylabel("rps")
        for x in t:
            p95, err = s["latency_p95"].get(x), s["error_rate"].get(x)
            if (p95 is not None and p95 == p95 and p95 > SLO_P95) or (err is not None and err == err and err > MAX_ERR):
                ax.axvspan((x - start) / 60, (x - start) / 60 + 10 / 60, color="#d62728", alpha=0.25, lw=0)
        if fault:
            ax.axvline(float(r["fault_at_min"]), color="black", ls="--", lw=1)
            ax.set_title(f"{r['label']}  ({r['start'][5:16]})  recovery {r['recovery_s']} s, NFR violation after the "
                         f"fault {r['nfr_violation_after_fault_s']} s, max {r['max_replicas_after_fault']} pods",
                         fontsize=9, loc="left")
        else:
            ax.set_title(f"{r['label']}  ({r['start'][5:16]})  NFR violation {r['nfr_violation_s']} s, "
                         f"{r['replica_minutes']} replica-min, {r['correct_prov_pct']}% correct", fontsize=9, loc="left")
    axes[-1][0].set_xlabel("minutes since load start (solid = desired pods, dotted = ready pods, grey = rps, red = "
                           "p95 > 0.35 s or errors > 1%" + (", dashed = fault)" if fault else ")"))
    fig.tight_layout()
    out = os.path.join(HERE, out_name)
    fig.savefig(out, dpi=110)
    plt.close(fig)
    return out


def exact_permutation_p(a, b):
    """One-sided exact permutation test that mean(a) < mean(b) (small n: enumerate every split)."""
    pooled = list(a) + list(b)
    observed = sum(a) / len(a) - sum(b) / len(b)
    total = extreme = 0
    for idx in combinations(range(len(pooled)), len(a)):
        ga = [pooled[i] for i in idx]
        gb = [pooled[i] for i in range(len(pooled)) if i not in idx]
        total += 1
        extreme += (sum(ga) / len(ga) - sum(gb) / len(gb)) <= observed + 1e-9
    return extreme / total


def statistics(df, faults):
    from scipy.stats import fisher_exact
    lines = ["# Statistics (exact tests; small n)", ""]
    for col, what in [("replica_minutes", "cost"), ("nfr_violation_s", "NFR violation")]:
        a = pd.to_numeric(df.loc[df["label"] == AGENT, col], errors="coerce").dropna().tolist()
        b = pd.to_numeric(df.loc[df["label"] == "hpa", col], errors="coerce").dropna().tolist()
        if len(a) >= 2 and len(b) >= 2:
            lines.append(f"- Normal load, {what} ({col}): agent (n={len(a)}, mean {sum(a)/len(a):.1f}) < hpa "
                         f"(n={len(b)}, mean {sum(b)/len(b):.1f}): one-sided exact permutation p = "
                         f"{exact_permutation_p(a, b):.3f}; the other way p = {exact_permutation_p(b, a):.3f}")
    pooled = [[0, 0], [0, 0]]
    for name, st in faults:
        rec = st["recovery_s"].astype(str) != "never"
        ag, hp = st["label"] == AGENT, st["label"] == "hpa"
        t = [[int((rec & ag).sum()), int((~rec & ag).sum())], [int((rec & hp).sum()), int((~rec & hp).sum())]]
        pooled = [[pooled[i][j] + t[i][j] for j in range(2)] for i in range(2)]
        if sum(t[0]) and sum(t[1]):
            p = fisher_exact(t, alternative="greater").pvalue
            lines.append(f"- {name}: recovered, agent {t[0][0]}/{sum(t[0])} vs hpa {t[1][0]}/{sum(t[1])}: "
                         f"one-sided Fisher exact p = {p:.4f}")
    if sum(pooled[0]) and sum(pooled[1]) and len(faults) > 1:
        p = fisher_exact(pooled, alternative="greater").pvalue
        lines.append(f"- Faults pooled: agent {pooled[0][0]}/{sum(pooled[0])} vs hpa {pooled[1][0]}/{sum(pooled[1])}: "
                     f"one-sided Fisher exact p = {p:.5f}")
    return lines + [""]


def runs(path, tag):
    df = pd.read_csv(path) if os.path.exists(path) else pd.DataFrame(columns=["label", "notes"])
    df = df[~df["label"].astype(str).str.contains("INVALID")]   # excluded runs stay in the CSV for the record
    if tag:
        df = df[df["notes"].astype(str) == tag]
    return df.reset_index(drop=True)


def text(value, empty):
    return empty if pd.isna(value) or value == "" else value


def main():
    tag = sys.argv[1] if len(sys.argv) > 1 else None
    path = os.path.join(HERE, "results_nfr.csv")
    df = runs(path, tag)
    md = [f"# Agent {AGENT.replace('llm-', '')} vs Kubernetes HPA (phase 2: NFRs at the ingress, request mix, "
          "open-model load)", "",
          f"Generated {datetime.now():%Y-%m-%d %H:%M}"
          + (f" from the runs of campaign `{tag}` only" if tag else " from every valid run") + ". Both strategies "
          "on the same deployment with the same readiness and liveness probes. Lower is better except correct "
          "provisioning.", "",
          "# Normal load (k6/baseline.js: 1 -> 2 -> 3 -> 2 -> 1 pods needed)", "", f"{len(df)} runs from `results_nfr.csv`.",
          "", table(df, COLUMNS), ""]
    frames = []
    for name, heading, explanation in FAULTS:
        fpath = os.path.join(HERE, f"results_nfr_{name}.csv")
        if not os.path.exists(fpath):
            continue
        st = runs(fpath, tag)
        md += [f"# {heading}", "", f"{len(st)} runs from `results_nfr_{name}.csv`. {explanation}", "",
               table(st, FAULT_COLUMNS), ""]
        agent_runs = st[st["label"] == AGENT]
        if len(agent_runs):
            md += ["Agent wake-ups per run (time, actions, verification):", ""]
            md += [f"- {r['start'][5:16]}: recovery {r['recovery_s']} s; {text(r.get('agent_actions'), 'no agent run logged')}"
                   for _, r in agent_runs.iterrows()]
            md.append("")
        hpa_runs = st[st["label"] == "hpa"]
        if len(hpa_runs):
            md += ["HPA replica changes per run (mm:ss from the start):", ""]
            md += [f"- {r['start'][5:16]}: recovery {r['recovery_s']} s; {text(r.get('replica_changes'), 'none')}; "
                   f"liveness restarts {r.get('liveness_restarts', '')}" for _, r in hpa_runs.iterrows()]
            md.append("")
        frames.append((name, st))
    md += statistics(df, frames)
    with open(os.path.join(HERE, "comparison_nfr.md"), "w") as f:
        f.write("\n".join(md))
    print("\n".join(md))
    if len(df):
        print("timelines:", timelines(df, "comparison_nfr_timelines.png"))
    for name, st in frames:
        if len(st):
            print("fault timelines:", timelines(st, f"comparison_nfr_{name}_timelines.png", fault=True))


if __name__ == "__main__":
    main()
